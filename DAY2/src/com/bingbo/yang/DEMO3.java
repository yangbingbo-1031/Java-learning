package com.bingbo.yang;

import java.util.Scanner;

public class DEMO3 {
    static void main(String[] args) {
        Scanner sc=new Scanner(System.in);
        // 从键盘台输入一个整数
        int num =sc.nextInt();
        System.out.println(num);
        // 从键盘台输入一个小数
        double num2=sc.nextDouble();
        System.out.println(num2);
        // 从键盘台输入一个字符串
        String str=sc.next();
        System.out.println(str);
    }
}
