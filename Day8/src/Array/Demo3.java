package Array;

public class Demo3 {
    public static void main(String[] args) {
        // 1.创建一个数组
        int arr [] = {12,13,14,15,16,17,18,19,20};
        // 2.获取数组长度
        System.out.println(arr.length);
        // 3.遍历数组
        for (int i = 0; i < arr.length; i++) {
            System.out.println(arr[i]);
        }

    }
}
